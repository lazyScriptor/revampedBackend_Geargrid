(async () => {
  try {
    await masterSequelize.authenticate();
    const { TranslationPack } = initMasterModels(masterSequelize);
    await masterSequelize.sync();

    const packs = [
      { language_code: "en", name: "English", native_name: "English", translations: en },
      { language_code: "si", name: "Sinhala", native_name: "සිංහල", translations: si },
    ];

    for (const p of packs) {
      const existing = await TranslationPack.findOne({
        where: { language_code: p.language_code },
      });
      if (existing) {
        await existing.update({
          name: p.name,
          native_name: p.native_name,
          translations: p.translations,
          version: existing.version + 1,
          is_active: true,
        });
        console.log(
          `↻ Updated pack ${p.language_code} (v${existing.version + 1}) — ${countKeys(p.translations)} keys`,
        );
      } else {
        await TranslationPack.create({
          language_code: p.language_code,
          name: p.name,
          native_name: p.native_name,
          translations: p.translations,
          version: 1,
          is_active: true,
        });
        console.log(
          `+ Created pack ${p.language_code} (v1) — ${countKeys(p.translations)} keys`,
        );
      }
    }

    console.log("✅ Translation packs seeded.");
    process.exit(0);
  } catch (err) {
    console.error("❌ Seed failed:", err.message);
    process.exit(1);
  }
})();

function countKeys(obj) {
  let n = 0;
  const walk = (o) => {
    for (const k of Object.keys(o)) {
      const v = o[k];
      if (v && typeof v === "object" && !Array.isArray(v)) walk(v);
      else n++;
    }
  };
  walk(obj);
  return n;
}
